create or replace function private.upsert_inventory_approval_notification_v1(
  p_request public.approval_requests
) returns void
language plpgsql volatile security definer
set search_path = public, private, pg_temp
as $$
declare
  v_notification_id public.notifications.id%type;
  v_action text := case p_request.request_type
    when 'restock' then 'Restock'
    when 'write_off' then 'Write-off'
    else 'Discount' end;
  v_title text;
  v_body text;
  v_target_roles text[];
  v_priority text;
  v_payload jsonb;
begin
  if p_request.status = 'pending' then
    v_title := v_action || ' approval requested';
    v_body := case when p_request.request_type = 'discount' then
      p_request.requested_by_name || ' requested a ' ||
      round(p_request.discount_effective_percentage, 2) ||
      '% discount (PHP ' || round(p_request.discount_amount, 2) || ').'
    else
      p_request.requested_by_name || ' requested ' || v_action || ' of ' ||
      p_request.requested_quantity || ' ' || p_request.unit || ' for ' ||
      p_request.product_name || '.' end;
    v_target_roles := array['admin']::text[];
    v_priority := 'high';
  else
    v_title := v_action || ' request ' || p_request.status;
    v_body := case when p_request.request_type = 'discount' then
      'Your ' || round(p_request.discount_effective_percentage, 2) ||
      '% discount request was ' || p_request.status || '.'
    else
      'Your ' || v_action || ' request for ' ||
      p_request.requested_quantity || ' ' || p_request.unit || ' of ' ||
      p_request.product_name || ' was ' || p_request.status || '.' end;
    v_target_roles := array[p_request.requested_by_role]::text[];
    v_priority := 'medium';
  end if;

  v_payload := jsonb_build_object(
    'category', 'inventoryApproval',
    'approvalRequestId', p_request.id,
    'requestType', p_request.request_type,
    'status', p_request.status,
    'stage', p_request.status,
    'productId', p_request.product_id,
    'productName', p_request.product_name,
    'quantity', p_request.requested_quantity,
    'unit', p_request.unit,
    'discountMode', p_request.discount_mode,
    'discountValue', p_request.discount_value,
    'discountAmount', p_request.discount_amount,
    'effectivePercentage', p_request.discount_effective_percentage,
    'subtotalAmount', p_request.subtotal_amount,
    'requestedById', p_request.requested_by_id,
    'requestedByName', p_request.requested_by_name,
    'recipientId', case when p_request.status = 'pending'
      then null else to_jsonb(p_request.requested_by_id) end
  );

  select notification.id into v_notification_id
  from public.notifications notification
  where notification.location_id = p_request.location_id::text
    and notification.is_resolved = false
    and notification.type = 'system'
    and notification.payload ->> 'category' = 'inventoryApproval'
    and notification.payload ->> 'approvalRequestId' = p_request.id::text
  order by notification.created_at, notification.id
  limit 1
  for update;

  if v_notification_id is null then
    insert into public.notifications (
      location_id, target_roles, title, body, type, priority, payload,
      created_at, is_resolved, resolved_at
    ) values (
      p_request.location_id::text, v_target_roles, v_title, v_body, 'system',
      v_priority, v_payload, now(), false, null
    ) returning id into v_notification_id;
  else
    update public.notifications
    set target_roles = v_target_roles,
        title = v_title,
        body = v_body,
        priority = v_priority,
        payload = v_payload,
        is_resolved = false,
        resolved_at = null
    where id = v_notification_id;

    update public.notification_reads
    set is_read = false,
        read_at = null,
        is_deleted = false,
        deleted_at = null
    where notification_id = v_notification_id;
  end if;

  update public.notifications notification
  set is_resolved = true,
      resolved_at = now()
  where notification.location_id = p_request.location_id::text
    and notification.id <> v_notification_id
    and notification.is_resolved = false
    and notification.type = 'system'
    and notification.payload ->> 'category' = 'inventoryApproval'
    and notification.payload ->> 'approvalRequestId' = p_request.id::text;
end;
$$;

revoke all on function private.upsert_inventory_approval_notification_v1(
  public.approval_requests
) from public, anon, authenticated;

create or replace function public.create_discount_approval_request_v1(
  p_session_token text,
  p_items jsonb,
  p_discount_mode text,
  p_discount_value numeric,
  p_reason text,
  p_checkout_token text
) returns jsonb
language plpgsql volatile security definer
set search_path = public, private, extensions, pg_temp
as $$
declare
  v_profile record;
  v_snapshot record;
  v_request public.approval_requests;
  v_limit numeric;
  v_reason text := nullif(trim(coalesce(p_reason, '')), '');
begin
  select * into v_profile
  from private.require_app_session_v1(p_session_token);
  if not found then raise exception 'Approval session is invalid or expired'; end if;
  if v_profile.role not in ('staff', 'cashier') then
    raise exception 'Only Cashier accounts may request discount approval';
  end if;
  if v_reason is null then
    raise exception 'A reason is required for discount approval';
  end if;

  select * into v_snapshot
  from private.discount_cart_snapshot_v1(
    v_profile.location_id, p_items, p_discount_mode, p_discount_value,
    p_reason, p_checkout_token
  );

  select coalesce(settings.cashier_auto_approved_discount_limit_pct, 10)
    into v_limit
  from public.store_settings settings
  where settings.location_id = v_profile.location_id;
  v_limit := coalesce(v_limit, 10);
  if v_snapshot.effective_percentage <= v_limit then
    raise exception 'This discount is within the Cashier auto-approved limit';
  end if;

  select request.* into v_request
  from public.approval_requests request
  where request.location_id = v_profile.location_id
    and request.requested_by_id = v_profile.profile_id
    and request.request_type = 'discount'
    and request.checkout_token = trim(p_checkout_token)
    and request.cart_fingerprint = v_snapshot.cart_fingerprint
    and request.status in ('pending', 'approved')
    and request.used_at is null
  order by request.requested_at desc
  limit 1;

  if found then return private.approval_request_json_v1(v_request); end if;

  insert into public.approval_requests (
    location_id, request_type, requested_by_id, requested_by_name,
    requested_by_role, reason, discount_mode, discount_value,
    discount_amount, discount_effective_percentage, subtotal_amount,
    cart_items, cart_fingerprint, checkout_token
  ) values (
    v_profile.location_id, 'discount', v_profile.profile_id,
    v_profile.profile_name, v_profile.role, v_reason,
    lower(trim(p_discount_mode)), p_discount_value,
    v_snapshot.discount_amount, v_snapshot.effective_percentage,
    v_snapshot.subtotal_amount, v_snapshot.normalized_items,
    v_snapshot.cart_fingerprint,
    trim(p_checkout_token)
  ) returning * into v_request;

  perform private.upsert_inventory_approval_notification_v1(v_request);
  return private.approval_request_json_v1(v_request);
end;
$$;

create or replace function public.discount_approval_request_v1(
  p_session_token text,
  p_request_id uuid
) returns jsonb
language plpgsql stable security definer
set search_path = public, private, extensions, pg_temp
as $$
declare
  v_profile record;
  v_request public.approval_requests;
begin
  select * into v_profile
  from private.require_app_session_v1(p_session_token);
  if not found then raise exception 'Approval session is invalid or expired'; end if;

  select request.* into v_request
  from public.approval_requests request
  where request.id = p_request_id
    and request.request_type = 'discount'
    and request.location_id = v_profile.location_id
    and (v_profile.role = 'admin'
